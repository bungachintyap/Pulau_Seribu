            <div class="lg1">
                <li class="list-group-item"><b><h1 style="font-weight: bold; letter-spacing: 2px; text-align: left; font-size: larger;">Wisata Air</h1></b></li>
                <p>
                    Keindahan alam daratan maupun bawah laut Pulau Pari tentunya tidak diragukan lagi. Buah hati anda pastinya tidak sabar 
                    untuk menikmati wahana-wahana watersports yang ada. Sambil menikmati pemandangan bawah laut yang mempesona, si kecil juga 
                    dapat mengenali berbagai spesies terumbu karang yang hidup di laut sekitar Pulau Pari.Ikan-ikan kecil dengan warna-warni 
                    yang cantik siap menyambut buah hati anda saat snorkeling. Jangan lupa mengabadikan momen ini menggunakan kamera khusus bawah air.  
                    Puas snorkeling di satu titik, anda bisa mencoba titik lainnya. Biasanya, paket wisata Pulau Pari sudah termasuk sewa alat snorkeling 
                    di 1 hingga  3 titik, tergantung paket yang anda ambil.
                </p>
                
                <li class="list-group-item"><b><h1 style="font-weight: bold; letter-spacing: 2px; text-align: left; font-size: larger;">Sunset & Sunrise</h1></b></li>
                <p>
                    Lengkapi pengalaman berwisata anda di Pulau Pari dengan menikmati keindahan alam di Bukit Matahari. Bukit ini tidaklah seperti kebanyakan. 
                    Anda tidak akan menemukan bukit hijau dengan pepohonan rindang di sini. Bukit Matahari tidak lebih dari gundukan pasir yang tidak jauh dari 
                    Dermaga Pulau Pari. Spot ini paling digemari oleh para ‘pemburu’ sunset dan sunrise.
                </p>
                <li class="list-group-item"><b><h1 style="font-weight: bold; letter-spacing: 2px; text-align: left; font-size: larger;">Hutan Mangrove</h1></b></li>
                <p>
                    Di pulau lainnya di Indonesia, pemerintah giat mempromosikan pelestarian alam melalui penanaman hutan mangrove. Di Pulau Pari, hutan mangrove 
                    tumbuh alamiah dan dikelola mandiri oleh penduduk setempat. Hutan mangrove menjadi salah satu objek wisata ilmu pengetahuan yang layak anda 
                    kunjungi. Tentunya, anda juga bisa menjadikannya sebagai background foto-foto yang cantik.
                </p>
            </div>
            <div class="lg2">
                <li class="list-group-item"><b><h1 style="font-weight: bold; letter-spacing: 2px; text-align: left; font-size: larger;">Wisata Pantai</h1></b></li>
                <p>
                    Wisata Pulau Pari didominasi oleh pantai-pantainya yang indah dan alami, terutama Pantai Pasir Perawan, Pantai Kresek, dan Pantai LIPI. 
                    Namanya saja unik, bukan?  Paket wisata yang tersedia umumnya sudah termasuk tiket masuk gratis ke tiga pantai ini. 
                    <ul>
                        <li>
                            <b>Pantai Pasir Perawan</b> <br> Pantai ini adalah objek wisata unggulan. Seperti namanya, pantai ini memang masih relatif 
                            terjaga keasliannya. Selain itu, ada juga cerita yang beredar tentang asal usul namanya. Fasilitas yang tersedia di 
                            sekitar pantai cukup memadai, seperti saung untuk berlindung dari sinar matahari, toilet, lapangan volley, kedai makanan 
                            dan minuman, serta musholla. 
                        </li> <br>
                        <li>
                            <b>Pantai Pasir Kresek</b> <br> Menurut informasi dari penduduk setempat, nama Pantai 
                            Pasir Kresek adalah singkatan dari Pantai Pasir Keren dan Seksi. Nama ini sesuai dengan tampilannya yang eksotis – 
                            perpaduan antara pasir putih dengan gradasi kecoklatan. Pohon pinus dan kelapa yang tumbuh di sekitar pantai menjadi 
                            pelindung bagi wisatawan dari sengatan sinar matahari. <br>Jika berwisata bersama buah hati anda, tidak ada salahnya mampir 
                            di fasilitas penangkaran biota laut yang tidak jauh dari pantai. Anda bisa melihat penangkaran bintang laut, ikan pari, 
                            bulu babi, dan penyu milik penduduk lokal. Meski cukup sederhana dan tampak seperti keramba, setidaknya anda dan si kecil 
                            bisa mendapatkan pengetahuan tentang siklus hidup biota laut ini. 
                        </li> <br>
                        <li>
                            <b>Pantai LIPI</b> <br> Seperti namanya, pantai ini dikelola 
                            oleh Lembaga Ilmu Pengetahuan Indonesia (LIPI) untuk keperluan penelitian. Sekali lagi, selain bersenang-senang, anda bisa 
                            mendapatkan ilmu pengetahuan baru dengan Paket Wisata Pulau Pari. Pantai ini adalah lokasi penangkaran hewan maupun tumbuhan laut.
                            <br>Lokasi pantai cukup jauh dari permukiman penduduk. Namun, sejumlah fasilitas telah tersedia untuk kenyamanan pengunjung. 
                            Bahkan, sarana akomodasi juga tersedia di sini. Selanjutnya, ada sarana lain seperti lapangan futsal, sarana untuk bersantai 
                            seperti ayunan, dan sebagainya.
                        </li>
                    </ul>
                </p>
            </div>
