    <h1 style="font-weight: bold; letter-spacing: 1.0mm; font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;">
            Pulau Pari — Detik Tenang di Pulau Pari
    </h1>

    <p style="font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; text-align: justify; margin-top: 0.4cm; margin-bottom: 1cm;">
        Pulau Pari merupakan salah satu destinasi wisata favorit di Kepulauan Seribu yang terkenal dengan keindahan 
        pantai berpasir putih dan air lautnya yang jernih. Terletak sekitar 1,5 jam perjalanan laut dari Jakarta, pulau 
        ini menawarkan suasana tenang dan alami, menjadikannya pilihan ideal untuk liburan singkat atau sekadar melepas 
        penat dari hiruk pikuk kota. Di Pulau Pari, wisatawan bisa menikmati berbagai aktivitas seru seperti snorkeling, 
        bersepeda keliling pulau, bermain kano, hingga bersantai di Pantai Perawan yang menjadi ikon utamanya. Selain keindahan 
        alam, keramahan penduduk lokal dan fasilitas wisata yang terus berkembang juga menambah kenyamanan bagi para pengunjung.
    </p>

