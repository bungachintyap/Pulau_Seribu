    <p style="font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;">
        Jika ingin menikmati liburan di tempat yang masih asri dan menyegarkan tanpa harus jauh-jauh meninggalkan Kota Jakarta, maka Kepulauan Seribu adalah pilihannya. 
        Di antara deretan pulau berpenduduk di Kepulauan Seribu, Pulau Harapan menawarkan keindahan yang tak bisa disangkal. 
        Alamnya yang masih alami, udara yang segar bebas dari polusi udara, serta suasananya yang nyaman selalu berhasil memikat wisatawan untuk datang berkunjung berulang-ulang ke pulau ini.
        <br><br>
        Pulau Harapan adalah salah satu kelurahan di Kepulauan Seribu Utara. Luasnya sekitar 48 hektar. 
        Di masa lalu, pulau ini dikenal sebagai “Pulau Pelemparan” karena daerah ini menjadi tujuan transmigrasi lokal dan relokasi penduduk dari Jakarta. 
        Jumlah penduduknya lebih dari 2.000 jiwa dan sebagian besar berasal dari etnis Bugis, Jawa, Mandar, dan dari Pulau Kelapa.
    </p>

