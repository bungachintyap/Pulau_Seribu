                    sebagai spot menarik bagi wisatawan. Jembatan sepanjang 800 meter ini menjadi icon wisata Pulau Tidung sebagai: 
                    <ul>
                        <li>Spot yang romantis untuk memadu kasih, terutama di kala sunset </li>
                        <li>Spot selfie yang cantik dengan latar belakang lautan lepas </li>
                        <li>Spot hiburan saat sore hari, karena pengunjung bisa melihat anak-anak setempat mandi di laut dan melompat dari jembatan</li>
                        <li>Spot adu nyali, untuk wisatawan yang ingin mencoba melompat dari jembatan dan kemudian mandi di laut.</li>
                    </ul>
                </p>
                <p style="font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;"> 
