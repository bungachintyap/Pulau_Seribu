                <li class="list-group-item""><b><p style="font-weight: bold; letter-spacing: 2px; text-align: left; font-size: larger;">Pulau Tidung, Kepulauan Seribu Jakarta</p></b></li><br>
                <p style="font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;">
                    Berbicara tentang Pulau Tidung, berarti yang dimaksud adalah dua pulau yang saling terhubung, yakni Pulau Tidung Besar dan 
                    Pulau Tidung Kecil. Pulau Tidung Besar dimanfaatkan untuk pemukiman penduduk, sedangkan Pulau Tidung Kecil adalah kawasan 
                    konservasi alam. Layaknya permukiman penduduk, Pulau Tidung Besar memiliki fasilitas sosial dan ekonomi untuk menunjang kehidupan masyarakat. 
                    Di sepanjang jalan utama, terdapat sekolah, rumah ibadah, sarana kesehatan, kantor pemerintahan, dan rumah-rumah penduduk. <br><br>Menurut sejarah, 
                    pulau ini telah dihuni penduduk sejak tahun 1800an. Seperti halnya pulau berpenduduk lain di Kepulauan Seribu, Pulau Tidung dihuni oleh 
                    masyarakat yang cukup heterogen. Menurut catatan, penduduk di pulau ini berasal dari beberapa wilayah dan etnis di tanah air, seperti Jawa, 
                    Kalimantan Timur, Kalimantan Barat, Banten, Bugis, Sumatera, Betawi, Sumbawa, dan Mandar. Jadi, masyarakatnya cukup terbuka kepada pendatang, 
                    karena penduduk setempat telah terbiasa bertinteraksi dengan berbagai etnis di tanah air. <br><br>Pulau Tidung terletak di Kecamatan Pulau Seribu Selatan. 
                    Berada di daerah selatan menunjukkan kalau pulau ini dekat dengan Kota Jakarta. Pulau ini adalah alternatif yang tepat untuk liburan pendek, seperti 
                    weekend. Untuk liburan ke Bali atau Lombok, anda tentu butuh waktu setidaknya seminggu. Namun, liburan ke Pulau Tidung bisa anda lakukan dalam waktu 
                    2 hari atau bahkan 1 hari saja. So, liburan yang singkat bukan lagi alasan untuk tidak kemana-mana….Di Pulau Tidung, anda bisa menghabiskan waktu 
                    libur dengan penuh kesan, dan menyegarkan tubuh dan fikiran anda untuk kembali beraktivitas seperti biasa.
                </p>
            </div>
