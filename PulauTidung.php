                    yang percaya bahwa pasangan yang sedang bertengkar bisa akur jika berkunjung ke jembatan ini. Percaya atau tidak, itu semua tergantung anda tentunya. 
                    <br><br>Jembatan Cinta awalnya dibangun dari kayu. Namun kini, jembatan ini telah dibangun permanen oleh pemerintah. Cat warna merah muda semakin menegaskan 
